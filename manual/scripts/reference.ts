// ── Doc comments, read exactly as src/client/workbench/schema.ts reads them ──

function docComments(src: string, iface: string): Record<string, string> {
  const start = src.indexOf(`export interface ${iface} {`);
  if (start < 0) return {};
  let depth = 0;
  let end = start;
  for (let i = src.indexOf('{', start); i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}' && --depth === 0) {
      end = i;
      break;
    }
  }
  const body = src.slice(start, end);
  const out: Record<string, string> = {};
  const re = /\/\*\*([\s\S]*?)\*\/\s*\n\s*([A-Za-z0-9_]+)\??\s*:/g;
  for (let m = re.exec(body); m; m = re.exec(body)) {
    out[m[2]] = m[1]
      .split('\n')
      .map((l) => l.replace(/^\s*\*\s?/, '').trim())
      .filter(Boolean)
      .join(' ');
  }
  return out;
}

