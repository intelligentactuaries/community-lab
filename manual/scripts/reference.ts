function write(rel: string, text: string) {
  const path = join(MANUAL, rel);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text.endsWith('\n') ? text : `${text}\n`);
  console.log(`reference: wrote manual/${rel}`);
}

