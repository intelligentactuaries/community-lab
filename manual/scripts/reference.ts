// ── Formatting ──

const esc = (s: string) => s.replace(/\|/g, '\\|');
const sentence = (s: string) => {
  const t = s.trim();
  return t && !/[.!?)]$/.test(t) ? `${t}.` : t;
};
const num = (x: number) => {
  if (Number.isInteger(x)) return Math.abs(x) >= 1_000 ? x.toLocaleString('en-GB') : String(x);
  return String(Number(x.toPrecision(6)));
};
const fmt = (v: unknown): string => {
  if (typeof v === 'number') return `\`${num(v)}\``;
  if (typeof v === 'boolean') return `\`${v}\``;
  if (typeof v === 'string') return `\`"${v}"\``;
  return `\`${JSON.stringify(v)}\``;
};

function describe(k: keyof ScenarioParams): string {
  const doc = DOCS[k] ? sentence(DOCS[k]) : '';
  const note = NOTES[k] ?? '';
  if (note && REPLACE.has(k)) return note;
  return [doc, note].filter(Boolean).join(' ');
}

function accepted(k: keyof ScenarioParams): string {
  if (NOT_PATCHABLE.has(k)) return k === 'seed' ? 'any text (a province file\'s `seed`)' : 'not settable from a file';
  const def = DEFAULT_PARAMS[k];
  if (k === 'educationMix') return 'six shares, normalised to sum to 1';
  if (typeof def === 'number') {
    const r = PARAM_RANGES[k];
    return r ? `${num(r[0])} to ${num(r[1])}` : 'any number';
  }
  if (typeof def === 'boolean') return '`true` or `false`';
  const c = CHOICES[k];
  if (c) return c.map((x) => `\`${x}\``).join(', ');
  if (k === 'startDate') return 'a date, `YYYY-MM-DD`';
  return 'a short text (60 characters at most)';
}

