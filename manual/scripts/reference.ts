// ── templates.md ──

const AUDIENCE: Record<string, string> = { actuarial: 'For actuaries', government: 'For governments', social: 'For social developers' };
const LABEL = new Map(METRICS.map((m) => [m.id, m.label]));

function shockText(s: Shock): string {
  const span = `from month ${s.fromMonth} for ${s.months} month${s.months === 1 ? '' : 's'}`;
  if (s.kind === 'mortality') {
    const ages = s.minAge !== undefined || s.maxAge !== undefined ? ` at ages ${s.minAge ?? 0} to ${s.maxAge ?? 110}` : ' at every age';
    return `mortality ×${num(s.factor ?? 1)}${ages}, ${span}`;
  }
  if (s.kind === 'repo') return `repo ${(s.bp ?? 0) >= 0 ? '+' : ''}${s.bp} bp, ${span}`;
  return `Brent ×${num(s.factor ?? 1)}, ${span}`;
}

